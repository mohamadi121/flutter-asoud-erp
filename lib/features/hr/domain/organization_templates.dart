import 'organization_chart.dart';

class OrganizationTemplate {
  const OrganizationTemplate(this.title, this.description, this.branches);
  final String title, description;
  final Map<String, List<String>> branches;

  // Suggested vacant positions, not invented employees or access roles.
  List<OrgPosition> get positions {
    final rows = <OrgPosition>[const OrgPosition(code: '1', title: 'مدیرعامل')];
    var branch = 0;
    for (final entry in {..._commonBranches, ...branches}.entries) {
      final code = '1${(++branch).toString().padLeft(2, '0')}';
      rows.add(OrgPosition(
          code: code, title: entry.key, parent: '1', department: entry.key));
      for (var i = 0; i < entry.value.length; i++) {
        rows.add(OrgPosition(
            code: '$code${(i + 1).toString().padLeft(2, '0')}',
            title: entry.value[i],
            parent: code,
            department: entry.key));
      }
    }
    return rows;
  }
}

